// Rootless install: versioned runtime directories with an atomic `current` symlink
// (old runtimes stay for rollback), a launcher, desktop entry, icon and URL schemes.
// The app's profile (~/.config/<App>) is never touched.
// Package install (installPackage): the same files in a conventional system layout,
// staged into a DESTDIR for a package manager, with no side effects.
'use strict';
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { ROOT, run } = require('./util.cjs');

// How a launcher finds its prefix and runtime: rootless installs resolve the prefix
// relative to the launcher and use opt/<install.id>/current; packages bake in the
// final prefix (validated by packagePrefix) and use lib/<install.id>.
function layoutLines(config, layout) {
  const { id: installId } = config.install;
  if (layout.prefix) return { comment: '', prefix: `prefix=${layout.prefix}`, appDir: `$prefix/lib/${installId}` };
  return {
    comment: '# Resolve relative to this launcher, including non-default prefixes.\n',
    prefix: 'prefix=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)',
    appDir: `$prefix/opt/${installId}/current`,
  };
}

// Values interpolated here are validated ids/prefixes (see apps.cjs).
function launcherSource(config, layout = {}) {
  const { id: installId } = config.install;
  const P = config.envPrefix;
  const lines = layoutLines(config, layout);
  return `#!/usr/bin/env bash
# Generated by electron-transplant for ${config.name}; ${layout.prefix ? 'part of its package' : 'reinstall to update'}.
set -euo pipefail
umask 077
${lines.comment}${lines.prefix}
app_dir="\${${P}_APP_DIR:-${lines.appDir}}"
[[ -x "$app_dir/electron" ]] || { printf '${config.name} runtime not found: %s\\n' "$app_dir" >&2; exit 1; }
log_dir="\${XDG_CACHE_HOME:-$HOME/.cache}/${installId}"
mkdir -p "$log_dir"
chmod 700 "$log_dir"
log_file="$log_dir/launcher.log"
if [[ -f "$log_file" ]] && (( $(stat -c %s "$log_file") > 5242880 )); then
  mv -f "$log_file" "$log_file.previous"
fi
export ELECTRON_IS_DEV=0
export ELECTRON_FORCE_IS_PACKAGED=true
# Set by Electron-based hosts (editors, agents); would make this run as plain Node.
unset ELECTRON_RUN_AS_NODE
# No sandbox-disabling switches: Chromium uses its user-namespace sandbox, and
# some apps (Linear) refuse to start with them.
args=()
# Native Wayland renders at the output's real density; ${P}_USE_WAYLAND=0 forces XWayland.
use_wayland="\${${P}_USE_WAYLAND:-auto}"
if [[ "$use_wayland" == 1 || ( "$use_wayland" == auto && -n "\${WAYLAND_DISPLAY:-}" ) ]]; then
  args+=(--ozone-platform=wayland --enable-wayland-ime)
else
  args+=(--ozone-platform=x11)
fi
cd "$HOME"
exec "$app_dir/electron" "\${args[@]}" "$@" >> "$log_file" 2>&1
`;
}

// A helper command runs one script from <prefix>/share/<install.id> with the app's
// own Electron in Node mode, so helpers need no system Node. Names are validated.
// iconPath: the installed icon relative to the prefix, or null.
function helperSource(config, helper, iconPath = null, layout = {}) {
  const { id: installId, command } = config.install;
  if (iconPath !== null && !/^[\w@.+\/-]+$/.test(iconPath)) throw Error(`Unexpected icon path ${iconPath}`);
  const P = config.envPrefix;
  const lines = layoutLines(config, layout);
  return `#!/usr/bin/env bash
# Generated by electron-transplant for ${config.name}; ${layout.prefix ? 'part of its package' : 'reinstall to update'}.
set -euo pipefail
${lines.prefix}
app_dir="\${${P}_APP_DIR:-${lines.appDir}}"
[[ -x "$app_dir/electron" ]] || { printf '${config.name} runtime not found: %s\\n' "$app_dir" >&2; exit 1; }
export ET_APP_LAUNCHER="$prefix/bin/${command}"
${iconPath ? `export ET_APP_ICON="$prefix/${iconPath}"\n` : ''}export ELECTRON_RUN_AS_NODE=1
exec "$app_dir/electron" "$prefix/share/${installId}/${helper.script}" "$@"
`;
}

function helperEntry(config, prefix, helper, icon) {
  const lines = [
    '[Desktop Entry]',
    'Version=1.0',
    'Type=Application',
    `Name=${oneLine(helper.name)}`,
    ...(helper.comment ? [`Comment=${oneLine(helper.comment)}`] : []),
    `Exec=${[quoteExec(path.join(prefix, 'bin', helper.command)), ...(helper.args ?? [])].join(' ')}`,
    `Icon=${oneLine(icon)}`,
    'Terminal=false',
    `Categories=${oneLine(config.install.categories ?? 'Utility;')}`,
    ...(helper.keywords ? [`Keywords=${oneLine(helper.keywords)}`] : []),
  ];
  return lines.join('\n') + '\n';
}

// Replaces <prefix>/share/<install.id> with the app's install.share directory.
function installShare(config, configDir, prefix) {
  return copyShare(config, configDir, path.join(prefix, 'share', config.install.id));
}

function copyShare(config, configDir, target) {
  const staging = `${target}.staging-${process.pid}`;
  fs.rmSync(staging, { recursive: true, force: true });
  fs.cpSync(path.join(configDir, config.install.share), staging, { recursive: true, filter: (src) => !/(^|\/)(__pycache__|node_modules|\.git)(\/|$)/.test(src) });
  fs.rmSync(target, { recursive: true, force: true });
  fs.renameSync(staging, target);
  return target;
}

// Desktop Entry spec: inside a quoted Exec argument, escape " ` $ and \\.
// Plain paths stay unquoted: xdg-utils' generic backend (xdg-mime query default,
// xdg-open outside GNOME/KDE) takes the first word of Exec literally, quotes
// included, and silently skips a handler whose program it can't find.
const quoteExec = (value) => (/^[\w@%+=:,.\/-]+$/.test(value) ? value : `"${value.replace(/["`$\\]/g, '\\$&')}"`);
const oneLine = (value) => String(value).replace(/[\r\n]+/g, ' ');

function desktopEntry(config, prefix, schemes, icon = config.install.id) {
  const lines = [
    '[Desktop Entry]',
    'Version=1.0',
    'Type=Application',
    // install.name tells it apart from another app of the same name (e.g. a wrapper).
    `Name=${oneLine(config.install.name ?? config.name)}`,
    `Comment=${oneLine(config.install.comment ?? `${config.name} — unofficial Linux port of the macOS app`)}`,
    // `--` ends Chromium switch parsing; apps read the URL from the last argument.
    `Exec=${quoteExec(path.join(prefix, 'bin', config.install.command))} -- %u`,
    `Icon=${oneLine(icon)}`,
    'Terminal=false',
    `Categories=${oneLine(config.install.categories ?? 'Utility;')}`,
    `StartupWMClass=${config.install.id}`,
  ];
  if (schemes.length) lines.push(`MimeType=${schemes.map((s) => `x-scheme-handler/${s};`).join('')}`);
  return lines.join('\n') + '\n';
}

function schemesFor(config, runtime) {
  const transplant = JSON.parse(fs.readFileSync(path.join(runtime, 'TRANSPLANT.json'), 'utf8'));
  return [...new Set([...(transplant.urlSchemes ?? []), ...(config.install.schemes ?? [])])].sort();
}

// GTK launchers that trust an icon cache can't see icons added after it was
// written. Regenerate an existing cache; never create one (-t: user theme
// directories have no index.theme).
function refreshIconCache(theme, log) {
  if (!fs.existsSync(path.join(theme, 'icon-theme.cache'))) return false;
  for (const tool of ['gtk-update-icon-cache', 'gtk4-update-icon-cache']) {
    try {
      run(tool, ['-f', '-q', '-t', theme]);
      return true;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  log(`warning: ${theme}/icon-theme.cache is stale and gtk-update-icon-cache is missing; launchers may not show the icon`);
  return false;
}

function install({ config, configDir, runtime, prefix, log = console.log }) {
  if (!path.isAbsolute(prefix)) throw Error('--prefix must be absolute');
  if (config.install.share && !configDir) throw Error(`${config.name}: install.share needs the app's config directory`);
  const transplant = JSON.parse(fs.readFileSync(path.join(runtime, 'TRANSPLANT.json'), 'utf8'));
  const { id: installId, command } = config.install;
  const base = path.join(prefix, 'opt', installId);
  const asarHash = crypto.createHash('sha256').update(fs.readFileSync(path.join(runtime, 'resources/app.asar'))).digest('hex').slice(0, 12);
  const id = `${transplant.version}-local-${asarHash}`;
  for (const dir of [base, path.join(prefix, 'bin'), path.join(prefix, 'share/applications')]) fs.mkdirSync(dir, { recursive: true });
  if (!fs.existsSync(path.join(base, id))) {
    const staging = path.join(base, `.${id}.staging`);
    fs.rmSync(staging, { recursive: true, force: true });
    fs.cpSync(runtime, staging, { recursive: true, verbatimSymlinks: true });
    fs.renameSync(staging, path.join(base, id));
  }
  const link = path.join(base, `.current.${process.pid}`);
  fs.rmSync(link, { force: true });
  fs.symlinkSync(id, link);
  fs.renameSync(link, path.join(base, 'current'));

  fs.writeFileSync(path.join(prefix, 'bin', command), launcherSource(config), { mode: 0o755 });
  fs.chmodSync(path.join(prefix, 'bin', command), 0o755);
  // Absolute icon path: some launchers (Vicinae) ignore ~/.local/share/icons/hicolor
  // because it has no index.theme, so a theme name alone shows a placeholder there.
  let icon = installId;
  if (transplant.iconSize && fs.existsSync(path.join(runtime, 'app-icon.png'))) {
    const theme = path.join(prefix, 'share/icons/hicolor');
    const iconDir = path.join(theme, `${transplant.iconSize}x${transplant.iconSize}`, 'apps');
    fs.mkdirSync(iconDir, { recursive: true });
    icon = path.join(iconDir, `${installId}.png`);
    fs.copyFileSync(path.join(runtime, 'app-icon.png'), icon);
    refreshIconCache(theme, log);
  }
  const schemes = schemesFor(config, runtime);
  const desktopFile = path.join(prefix, 'share/applications', `${installId}.desktop`);
  fs.writeFileSync(desktopFile, desktopEntry(config, prefix, schemes, icon));
  const shared = config.install.share ? installShare(config, configDir, prefix) : null;
  for (const helper of config.install.helpers ?? []) {
    const iconPath = path.isAbsolute(icon) && icon.startsWith(prefix + path.sep) ? path.relative(prefix, icon) : null;
    fs.writeFileSync(path.join(prefix, 'bin', helper.command), helperSource(config, helper, iconPath), { mode: 0o755 });
    fs.chmodSync(path.join(prefix, 'bin', helper.command), 0o755);
    fs.writeFileSync(path.join(prefix, 'share/applications', `${helper.command}.desktop`), helperEntry(config, prefix, helper, icon));
  }
  fs.writeFileSync(path.join(base, 'SOURCE-CHECKOUT'), `${ROOT}\n`);
  try { run('update-desktop-database', [path.join(prefix, 'share/applications')]); } catch {}
  const dataHome = process.env.XDG_DATA_HOME || path.join(process.env.HOME, '.local/share');
  // install.defaultSchemes limits which registered schemes this app takes over as
  // the default handler; the others stay with whichever app handles them now.
  const defaults = schemes.filter((s) => !config.install.defaultSchemes || config.install.defaultSchemes.includes(s));
  if (path.join(prefix, 'share') === dataHome) {
    for (const scheme of defaults) {
      try { run('xdg-mime', ['default', `${installId}.desktop`, `x-scheme-handler/${scheme}`]); } catch {}
    }
  }
  log(`Installed: ${base}/current -> ${id}`);
  if (shared) log(`Shared files: ${shared}`);
  for (const helper of config.install.helpers ?? []) log(`Helper: ${helper.command}`);
  const kept = schemes.filter((s) => !defaults.includes(s));
  log(`Launch: ${command}  (schemes: ${schemes.join(', ') || 'none'}${kept.length ? `; registered but not made default: ${kept.join(', ')}` : ''}; profile untouched)`);
  return { base, id, schemes, defaults };
}

// A package's final prefix (/usr, a Nix store path) is baked into launchers and
// desktop entries unquoted (no % either: Exec field codes), so it is limited to
// plain path characters.
function packagePrefix(prefix) {
  const plain = String(prefix ?? '').replace(/\/+$/, '');
  if (!/^(\/[\w@+=:,.-]+)+$/.test(plain) || plain.split('/').some((part) => part === '.' || part === '..')) {
    throw Error(`--prefix must be an absolute plain path other than /: ${prefix}`);
  }
  return plain;
}

// Package layout, staged under destdir (default: none, e.g. a Nix $out as prefix):
//   <prefix>/lib/<install.id>/                      the runtime (Electron + app)
//   <prefix>/bin/<command>, <helper commands>       launchers
//   <prefix>/share/applications/<install.id>.desktop (MimeType: its URL schemes)
//   <prefix>/share/icons/hicolor/<N>x<N>/apps/<install.id>.png
//   <prefix>/share/<install.id>/                    install.share, if any
//   <prefix>/share/licenses/<install.id>/           Electron, Chromium and electron-transplant licences
// No versioned directories (the package manager keeps versions), nothing outside
// destdir, no desktop-database, icon-cache or default-handler updates (the package
// manager's hooks do those), and no record of this checkout.
function installPackage({ config, configDir, runtime, prefix: finalPrefix, destdir = '', log = console.log }) {
  const prefix = packagePrefix(finalPrefix);
  if (destdir && !path.isAbsolute(destdir)) throw Error('--destdir must be absolute');
  if (config.install.share && !configDir) throw Error(`${config.name}: install.share needs the app's config directory`);
  const transplant = JSON.parse(fs.readFileSync(path.join(runtime, 'TRANSPLANT.json'), 'utf8'));
  if (transplant.app !== undefined && transplant.app !== config.id) throw Error(`${runtime} is a ${transplant.app} build, not ${config.id}`);
  const { id: installId, command } = config.install;
  const root = path.join(destdir || '/', prefix);
  const staged = (...parts) => path.join(root, ...parts);
  const final = (...parts) => path.join(prefix, ...parts);
  const layout = { prefix };
  for (const dir of ['lib', 'bin', 'share/applications', `share/licenses/${installId}`]) fs.mkdirSync(staged(dir), { recursive: true });

  const lib = staged('lib', installId);
  fs.rmSync(lib, { recursive: true, force: true });
  fs.cpSync(runtime, lib, { recursive: true, verbatimSymlinks: true });
  const write = (file, text, mode = 0o644) => {
    fs.writeFileSync(file, text, { mode });
    fs.chmodSync(file, mode);
  };
  write(staged('bin', command), launcherSource(config, layout), 0o755);

  // By theme name: the system hicolor theme (unlike ~/.local/share/icons) has an index.theme.
  let iconPath = null;
  if (transplant.iconSize && fs.existsSync(path.join(runtime, 'app-icon.png'))) {
    iconPath = path.join('share/icons/hicolor', `${transplant.iconSize}x${transplant.iconSize}`, 'apps', `${installId}.png`);
    fs.mkdirSync(path.dirname(staged(iconPath)), { recursive: true });
    fs.copyFileSync(path.join(runtime, 'app-icon.png'), staged(iconPath));
  }
  const icon = installId;
  const schemes = schemesFor(config, runtime);
  write(staged('share/applications', `${installId}.desktop`), desktopEntry(config, prefix, schemes, icon));
  if (config.install.share) copyShare(config, configDir, staged('share', installId));
  for (const helper of config.install.helpers ?? []) {
    write(staged('bin', helper.command), helperSource(config, helper, iconPath, layout), 0o755);
    write(staged('share/applications', `${helper.command}.desktop`), helperEntry(config, prefix, helper, icon));
  }
  const licences = staged('share/licenses', installId);
  for (const [from, to] of [[path.join(runtime, 'LICENSE'), 'LICENSE.electron'], [path.join(runtime, 'LICENSES.chromium.html'), 'LICENSES.chromium.html'], [path.join(ROOT, 'LICENSE'), 'LICENSE.electron-transplant']]) {
    if (fs.existsSync(from)) fs.copyFileSync(from, path.join(licences, to));
  }
  log(`Staged ${config.name} ${transplant.version} in ${root} for ${final()}`);
  log(`Launch: ${final('bin', command)}  (schemes: ${schemes.join(', ') || 'none'})`);
  return { root, lib, schemes };
}

module.exports = { install, installPackage, packagePrefix, launcherSource, helperSource, helperEntry, desktopEntry, quoteExec, refreshIconCache };
