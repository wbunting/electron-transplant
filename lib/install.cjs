// Rootless install: versioned runtime directories with an atomic `current` symlink
// (old runtimes stay for rollback), a launcher, desktop entry, icon and URL schemes.
// The app's profile (~/.config/<App>) is never touched.
'use strict';
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { ROOT, run } = require('./util.cjs');

// Values interpolated here are validated ids/prefixes (see apps.cjs).
function launcherSource(config) {
  const { id: installId } = config.install;
  const P = config.envPrefix;
  return `#!/usr/bin/env bash
# Generated by electron-transplant for ${config.name}; reinstall to update.
set -euo pipefail
umask 077
# Resolve relative to this launcher, including non-default prefixes.
prefix=$(cd -- "$(dirname -- "\${BASH_SOURCE[0]}")/.." && pwd)
app_dir="\${${P}_APP_DIR:-$prefix/opt/${installId}/current}"
[[ -x "$app_dir/electron" ]] || { printf '${config.name} runtime not found: %s\\n' "$app_dir" >&2; exit 1; }
log_dir="\${XDG_CACHE_HOME:-$HOME/.cache}/${installId}"
mkdir -p "$log_dir"
chmod 700 "$log_dir"
log_file="$log_dir/launcher.log"
if [[ -f "$log_file" ]] && (( $(stat -c %s "$log_file") > 5242880 )); then
  mv -f "$log_file" "$log_file.previous"
fi
export ELECTRON_IS_DEV=0
export ELECTRON_FORCE_IS_PACKAGED=true
# Set by Electron-based hosts (editors, agents); would make this run as plain Node.
unset ELECTRON_RUN_AS_NODE
# No sandbox-disabling switches: Chromium uses its user-namespace sandbox, and
# some apps (Linear) refuse to start with them.
args=()
# Native Wayland renders at the output's real density; ${P}_USE_WAYLAND=0 forces XWayland.
use_wayland="\${${P}_USE_WAYLAND:-auto}"
if [[ "$use_wayland" == 1 || ( "$use_wayland" == auto && -n "\${WAYLAND_DISPLAY:-}" ) ]]; then
  args+=(--ozone-platform=wayland --enable-wayland-ime)
else
  args+=(--ozone-platform=x11)
fi
cd "$HOME"
exec "$app_dir/electron" "\${args[@]}" "$@" >> "$log_file" 2>&1
`;
}

// Desktop Entry spec: inside a quoted Exec argument, escape " ` $ and \\.
const quoteExec = (value) => `"${value.replace(/["`$\\]/g, '\\$&')}"`;
const oneLine = (value) => String(value).replace(/[\r\n]+/g, ' ');

function desktopEntry(config, prefix, schemes, icon = config.install.id) {
  const lines = [
    '[Desktop Entry]',
    'Version=1.0',
    'Type=Application',
    `Name=${oneLine(config.name)}`,
    `Comment=${oneLine(config.install.comment ?? `${config.name} — unofficial Linux port of the macOS app`)}`,
    // `--` ends Chromium switch parsing; apps read the URL from the last argument.
    `Exec=${quoteExec(path.join(prefix, 'bin', config.install.command))} -- %u`,
    `Icon=${oneLine(icon)}`,
    'Terminal=false',
    `Categories=${oneLine(config.install.categories ?? 'Utility;')}`,
    `StartupWMClass=${config.install.id}`,
  ];
  if (schemes.length) lines.push(`MimeType=${schemes.map((s) => `x-scheme-handler/${s};`).join('')}`);
  return lines.join('\n') + '\n';
}

function schemesFor(config, runtime) {
  const transplant = JSON.parse(fs.readFileSync(path.join(runtime, 'TRANSPLANT.json'), 'utf8'));
  return [...new Set([...(transplant.urlSchemes ?? []), ...(config.install.schemes ?? [])])].sort();
}

// GTK launchers that trust an icon cache can't see icons added after it was
// written. Regenerate an existing cache; never create one (-t: user theme
// directories have no index.theme).
function refreshIconCache(theme, log) {
  if (!fs.existsSync(path.join(theme, 'icon-theme.cache'))) return false;
  for (const tool of ['gtk-update-icon-cache', 'gtk4-update-icon-cache']) {
    try {
      run(tool, ['-f', '-q', '-t', theme]);
      return true;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  log(`warning: ${theme}/icon-theme.cache is stale and gtk-update-icon-cache is missing; launchers may not show the icon`);
  return false;
}

function install({ config, runtime, prefix, log = console.log }) {
  if (!path.isAbsolute(prefix)) throw Error('--prefix must be absolute');
  const transplant = JSON.parse(fs.readFileSync(path.join(runtime, 'TRANSPLANT.json'), 'utf8'));
  const { id: installId, command } = config.install;
  const base = path.join(prefix, 'opt', installId);
  const asarHash = crypto.createHash('sha256').update(fs.readFileSync(path.join(runtime, 'resources/app.asar'))).digest('hex').slice(0, 12);
  const id = `${transplant.version}-local-${asarHash}`;
  for (const dir of [base, path.join(prefix, 'bin'), path.join(prefix, 'share/applications')]) fs.mkdirSync(dir, { recursive: true });
  if (!fs.existsSync(path.join(base, id))) {
    const staging = path.join(base, `.${id}.staging`);
    fs.rmSync(staging, { recursive: true, force: true });
    fs.cpSync(runtime, staging, { recursive: true, verbatimSymlinks: true });
    fs.renameSync(staging, path.join(base, id));
  }
  const link = path.join(base, `.current.${process.pid}`);
  fs.rmSync(link, { force: true });
  fs.symlinkSync(id, link);
  fs.renameSync(link, path.join(base, 'current'));

  fs.writeFileSync(path.join(prefix, 'bin', command), launcherSource(config), { mode: 0o755 });
  fs.chmodSync(path.join(prefix, 'bin', command), 0o755);
  // Absolute icon path: some launchers (Vicinae) ignore ~/.local/share/icons/hicolor
  // because it has no index.theme, so a theme name alone shows a placeholder there.
  let icon = installId;
  if (transplant.iconSize && fs.existsSync(path.join(runtime, 'app-icon.png'))) {
    const theme = path.join(prefix, 'share/icons/hicolor');
    const iconDir = path.join(theme, `${transplant.iconSize}x${transplant.iconSize}`, 'apps');
    fs.mkdirSync(iconDir, { recursive: true });
    icon = path.join(iconDir, `${installId}.png`);
    fs.copyFileSync(path.join(runtime, 'app-icon.png'), icon);
    refreshIconCache(theme, log);
  }
  const schemes = schemesFor(config, runtime);
  const desktopFile = path.join(prefix, 'share/applications', `${installId}.desktop`);
  fs.writeFileSync(desktopFile, desktopEntry(config, prefix, schemes, icon));
  fs.writeFileSync(path.join(base, 'SOURCE-CHECKOUT'), `${ROOT}\n`);
  try { run('update-desktop-database', [path.join(prefix, 'share/applications')]); } catch {}
  const dataHome = process.env.XDG_DATA_HOME || path.join(process.env.HOME, '.local/share');
  if (path.join(prefix, 'share') === dataHome) {
    for (const scheme of schemes) {
      try { run('xdg-mime', ['default', `${installId}.desktop`, `x-scheme-handler/${scheme}`]); } catch {}
    }
  }
  log(`Installed: ${base}/current -> ${id}`);
  log(`Launch: ${command}  (schemes: ${schemes.join(', ') || 'none'}; profile untouched)`);
  return { base, id, schemes };
}

module.exports = { install, launcherSource, desktopEntry, quoteExec, refreshIconCache };
