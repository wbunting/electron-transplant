// Native code in a transplanted app. Every native module the app ships is handled
// by its config entry; afterwards nothing Mach-O (or Windows, or non-x86-64 ELF)
// may remain anywhere in the app.
//
//   shim         replace the module with a JS file from the app's config directory
//   stub         generate a module whose listed exports record the call and throw
//   remove       delete paths (usually build/) when the module has its own Linux path
//   npm-prebuild copy files from the module's official npm tarball (integrity-pinned),
//                e.g. a Node-API prebuild that is ABI-stable across Electron versions
//
// Addons that are not packages (e.g. Figma's bindings.node beside main.js) are
// listed by path in nativeFiles; `remove` is the only action, for files the app
// never loads on Linux (its config says why).
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { cacheDir, download, verify, run, walk } = require('./util.cjs');

const MACH_O = new Set(['feedface', 'feedfacf', 'cefaedfe', 'cffaedfe', 'cafebabe', 'bebafeca']);
const EM_X86_64 = 0x3e;

function binaryKind(file) {
  const fd = fs.openSync(file, 'r');
  try {
    const header = Buffer.alloc(20);
    const read = fs.readSync(fd, header, 0, 20, 0);
    const magic = header.subarray(0, 4).toString('hex');
    if (MACH_O.has(magic)) return 'mach-o';
    if (magic === '7f454c46') return read >= 20 && header.readUInt16LE(18) === EM_X86_64 ? 'elf-x86-64' : 'elf-other';
    if (header.subarray(0, 2).toString('latin1') === 'MZ' && /\.(exe|dll|node)$/i.test(file)) return 'pe';
    return null;
  } finally {
    fs.closeSync(fd);
  }
}

// Binaries that cannot run here: anything but x86-64 ELF.
function foreignBinaries(dir) {
  const found = [];
  walk(dir, (file) => {
    const kind = binaryKind(file);
    if (kind && kind !== 'elf-x86-64') found.push({ file: path.relative(dir, file), kind });
  });
  return found;
}

function stubSource(name, exportsList) {
  const body = exportsList.map((exportName) => `  ${JSON.stringify(exportName)}: unavailable(${JSON.stringify(exportName)}),`).join('\n');
  return `// Generated by electron-transplant: ${name} is native macOS/Windows code with no
// Linux build. Calls are recorded by the compat recorder, then throw.
'use strict';
const record = (api) => globalThis[Symbol.for('electron-transplant.recorder')]?.record({ kind: 'native-shim', api });
function unavailable(exportName) {
  return function () {
    record(${JSON.stringify(name)} + '.' + exportName);
    throw new Error(${JSON.stringify(name)} + ' is not available on Linux');
  };
}
module.exports = {
${body}
  linuxShim: true,
};
`;
}

// Points the module's package.json at a Linux entry and drops its compiled output.
function replaceEntry(moduleDir, source) {
  fs.rmSync(path.join(moduleDir, 'build'), { recursive: true, force: true });
  fs.writeFileSync(path.join(moduleDir, 'linux.cjs'), source);
  const pkgPath = path.join(moduleDir, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  pkg.main = './linux.cjs';
  pkg.os = ['linux'];
  delete pkg.gypfile;
  delete pkg.exports;
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
}

function insideModule(moduleDir, relative) {
  const target = path.resolve(moduleDir, relative);
  if (!target.startsWith(moduleDir + path.sep)) throw Error(`Path escapes module: ${relative}`);
  return target;
}

async function npmPrebuild(moduleDir, spec) {
  const pkg = JSON.parse(fs.readFileSync(path.join(moduleDir, 'package.json'), 'utf8'));
  if (pkg.version !== spec.version) {
    throw Error(`${spec.package}: app ships ${pkg.version}, config pins ${spec.version}; update the config`);
  }
  const base = spec.package.replace(/^@[^/]+\//, '');
  const tarball = path.join(cacheDir('npm'), `${spec.package.replace('/', '+')}-${spec.version}.tgz`);
  await download(`https://registry.npmjs.org/${spec.package}/-/${base}-${spec.version}.tgz`, tarball);
  await verify(tarball, spec.integrity);
  const unpacked = fs.mkdtempSync(path.join(cacheDir('npm'), 'unpack-'));
  try {
    for (const from of Object.keys(spec.files)) {
      run('tar', ['-xzf', tarball, '-C', unpacked, `package/${from}`]);
    }
    for (const relative of spec.remove ?? []) fs.rmSync(insideModule(moduleDir, relative), { recursive: true, force: true });
    for (const [from, to] of Object.entries(spec.files)) {
      const target = insideModule(moduleDir, to);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.copyFileSync(path.join(unpacked, 'package', from), target);
    }
  } finally {
    fs.rmSync(unpacked, { recursive: true, force: true });
  }
}

async function handleNatives(appDir, natives, configDir) {
  const results = [];
  for (const [name, spec] of Object.entries(natives ?? {})) {
    const moduleDir = path.join(appDir, 'node_modules', name);
    if (!fs.existsSync(path.join(moduleDir, 'package.json'))) throw Error(`Native module missing from app: ${name}`);
    switch (spec.action) {
      case 'shim':
        replaceEntry(moduleDir, fs.readFileSync(path.join(configDir, spec.shim), 'utf8'));
        break;
      case 'stub':
        replaceEntry(moduleDir, stubSource(name, spec.exports ?? []));
        break;
      case 'remove':
        for (const relative of spec.paths) fs.rmSync(insideModule(moduleDir, relative), { recursive: true, force: true });
        break;
      case 'npm-prebuild':
        await npmPrebuild(moduleDir, spec);
        break;
      default:
        throw Error(`${name}: unknown native action ${spec.action}`);
    }
    results.push([name, spec.action]);
  }
  return results;
}

function handleNativeFiles(appDir, nativeFiles = {}) {
  const root = path.resolve(appDir);
  const results = [];
  for (const [file, spec] of Object.entries(nativeFiles)) {
    const target = path.resolve(root, file);
    if (!target.startsWith(root + path.sep)) throw Error(`Native file outside app: ${file}`);
    if (!fs.existsSync(target)) throw Error(`Native file missing from app: ${file}`);
    // Only foreign binaries: a config entry must not delete the app's own code.
    if (!binaryKind(target) || binaryKind(target) === 'elf-x86-64') throw Error(`${file} is not a foreign native binary`);
    if (spec.action !== 'remove') throw Error(`${file}: unknown native file action ${spec.action}`);
    fs.rmSync(target);
    results.push([file, spec.action]);
  }
  return results;
}

module.exports = { handleNatives, handleNativeFiles, foreignBinaries, binaryKind, stubSource };
